import React, { useEffect } from 'react'
import { useNavigate } from 'react-router-dom'
import { Download, RotateCcw } from 'lucide-react'
import ResultCard from '../components/ResultCard'
import Disclaimer from '../components/Disclaimer'
import { useAnalysis } from '../context/AnalysisContext'

function buildReport({ prediction, confidence, fileName }) {
  const timestamp = new Date().toLocaleString()
  return `NEUROSCAN AI — ANALYSIS REPORT
================================

Generated: ${timestamp}
Image file: ${fileName || 'N/A'}

RESULT
------
Predicted class: ${prediction}
Model confidence: ${Math.round((confidence ?? 0) * 100)}%

DISCLAIMER
----------
This report is generated by an AI research model for educational and
research purposes only. It is NOT a medical diagnosis. Please consult a
qualified medical professional for any health concerns or before making
any medical decisions.

--------------------------------
NeuroScan AI · neuroscan-ai
`
}

export default function Results() {
  const navigate = useNavigate()
  const { file, previewUrl, result, reset } = useAnalysis()

  useEffect(() => {
    if (!result) {
      navigate('/analyze', { replace: true })
    }
  }, [result, navigate])

  if (!result) return null

  const handleDownload = () => {
    const text = buildReport({ ...result, fileName: file?.name })
    const blob = new Blob([text], { type: 'text/plain;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const a = document.createElement('a')
    a.href = url
    a.download = 'neuroscan-ai-report.txt'
    document.body.appendChild(a)
    a.click()
    a.remove()
    URL.revokeObjectURL(url)
  }

  const handleAnalyzeAnother = () => {
    reset()
    navigate('/analyze')
  }

  return (
    <div className="container-page py-16 sm:py-20">
      <div className="mx-auto max-w-2xl text-center">
        <span className="font-mono text-xs font-semibold uppercase tracking-wide text-accent-600">
          Step 2 of 2
        </span>
        <h1 className="mt-3 font-display text-3xl font-semibold text-slate-900 sm:text-4xl">
          Analysis complete
        </h1>
        <p className="mt-3 text-slate-500">
          Here's what the model found in your uploaded scan.
        </p>
      </div>

      <div className="mx-auto mt-10 grid max-w-4xl gap-6 lg:grid-cols-2">
        <div className="overflow-hidden rounded-3xl border border-slate-100 bg-slate-900 shadow-soft">
          <img
            src={previewUrl}
            alt="Analyzed MRI scan"
            className="mx-auto h-full max-h-[420px] w-full object-contain"
          />
        </div>

        <ResultCard prediction={result.prediction} confidence={result.confidence} />
      </div>

      <div className="mx-auto mt-6 max-w-4xl">
        <Disclaimer compact />
      </div>

      <div className="mx-auto mt-8 flex max-w-4xl flex-col justify-center gap-3 sm:flex-row">
        <button
          onClick={handleAnalyzeAnother}
          className="flex items-center justify-center gap-2 rounded-full border border-slate-200 bg-white px-6 py-3 text-sm font-semibold text-slate-700 transition-colors hover:bg-slate-50"
        >
          <RotateCcw size={16} />
          Analyze Another Image
        </button>
        <button
          onClick={handleDownload}
          className="flex items-center justify-center gap-2 rounded-full bg-grad-primary px-6 py-3 text-sm font-semibold text-white shadow-soft transition-transform hover:scale-[1.02] active:scale-[0.98]"
        >
          <Download size={16} />
          Download Report
        </button>
      </div>
    </div>
  )
}
